// 此處資料表結合：
//   - 歷史值：使用 Espenak & Meeus 之多項式擬合（−4000 到 2005）
//   - 近年觀測：IERS Bulletin A 實測值
//   - 預測值：基於 NASA JPL DE440s 之擬合（2016 起）
// 每組分段以 5 個值表達：[起年 y, c0, c1, c2, c3]，計算式：
//   ΔT(year) = c0 + c1·t + c2·t² + c3·t³，其中 t = (year − y) / 10

