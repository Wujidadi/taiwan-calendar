/** 二次外推（用於資料表外的年份） */
function extrapolateDeltaT(year: number, accel: number): number {
  const dy = (year - 1820) / 100
  return -20 + accel * dy * dy
}

/**
 * 計算指定公曆年的 ΔT（秒）。
 *
 * 表內年份用三次多項式擬合插值；表外年份用二次外推
 * （加速度係數參考瑞士星曆表 31，NASA 為 32，skmap 為 29）。
 */
export function computeDeltaT(year: number): number {
  const d = DELTA_T_TABLE
  const y0 = d[d.length - 2]! // 表中最後一年
  const t0 = d[d.length - 1]! // 該年的 ΔT
  if (year >= y0) {
    const accel = 31
    if (year > y0 + 100) return extrapolateDeltaT(year, accel)
    const v = extrapolateDeltaT(year, accel)
    const dv = extrapolateDeltaT(y0, accel) - t0
    return v - (dv * (y0 + 100 - year)) / 100
  }
  let i = 0
  for (; i < d.length; i += 5) {
    if (year < d[i + 5]!) break
  }
  const t1 = ((year - d[i]!) / (d[i + 5]! - d[i]!)) * 10
  const t2 = t1 * t1
  const t3 = t2 * t1
  return d[i + 1]! + d[i + 2]! * t1 + d[i + 3]! * t2 + d[i + 4]! * t3
}

/**
 * 從 J2000 起算的儒略日數，回傳 ΔT（以「日」為單位）。
 * 適合直接加到 UT 儒略日上以得到 TT。
 *
 * @param t J2000 起算之儒略日數（即 JD − 2451545）
 */
export function deltaT(t: number): number {
  return computeDeltaT(t / 365.2425 + 2000) / SECONDS_PER_DAY
}
